const ANCHOR = new Date(2024, 0, 1).getTime();

/** 按日期在 64 卦中循环取当日一卦（与《周易》传统顺序一致） */
export function getDailyHexagram(year: number, month: number, day: number): DailyHexagramEntry {
  const t = new Date(year, month - 1, day).getTime();
  const days = Math.floor((t - ANCHOR) / 86_400_000);
  const idx = ((days % 64) + 64) % 64;
  return DAILY_HEXAGRAM_ENTRIES[idx]!;
}
